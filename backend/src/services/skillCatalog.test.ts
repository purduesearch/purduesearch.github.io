import assert from "node:assert/strict";
import { canonicalMap, identityIds, sharingProjection, projectedDisputes, projectEvidence, mergeProblem, proposalProblem } from "./skillCatalogCore.js";
import { assessMember, type EvidenceInput } from "./skillScoringCore.js";
import { matchOpportunity, validateGoals } from "./skillWorkspaceCore.js";

const nodes = [{ id: "a", canonicalId: "b" }, { id: "b", canonicalId: "c" }, { id: "c" }];
const map = canonicalMap(nodes);
assert.equal(map.get("a"), "c");
assert.deepEqual(identityIds("a", map), ["a", "b", "c"]);
assert.throws(() => canonicalMap([{ id: "a", canonicalId: "b" }, { id: "b", canonicalId: "a" }]), /cycle/);
assert.throws(() => canonicalMap([{ id: "a", canonicalId: "missing" }]), /Missing/);
assert.equal(sharingProjection(map, new Map([["a", true], ["b", true]])).get("c"), false, "absent choices never broaden sharing");
assert.equal(sharingProjection(map, new Map([["a", true], ["b", false], ["c", true]])).get("c"), false);
assert.equal(sharingProjection(map, new Map([["a", true], ["b", true], ["c", true]])).get("c"), true);
assert.deepEqual([...projectedDisputes(["a"], map)], ["c"]);

const item: EvidenceInput = { id: "e1", source: "GITHUB", projectId: "p1", occurredAt: new Date("2026-10-10"), contribution: "AUTHORED", complexity: 3, outcome: "SHIPPED", skills: [{ skillId: "a", fit: .8 }, { skillId: "c", fit: .7 }], contributionKey: "task:1" };
assert.equal(projectEvidence([item], map)[0].skills.length, 1, "two aliases on one artifact count once");
const linked = projectEvidence([item, { ...item, id: "e2", source: "TASK", skills: [{ skillId: "b", fit: .8 }, { skillId: "other", fit: .9 }] }], map);
const assessed = assessMember(linked, new Date("2026-10-16"));
assert.equal(assessed.get("c")?.evidenceCount, 1, "linked task and PR do not double credit");
assert.equal(assessed.get("other")?.evidenceCount, 1, "a corroborating record may support a distinct skill");
assert.equal(projectEvidence([item, { ...item, id: "e2", projectId: "p2" }], map).length, 2, "project boundaries prevent accidental grouping");
assert.equal(projectEvidence([item, { ...item, id: "e2", contributionKey: null }], map).length, 2, "similar unlinked work remains independent");
const a = { id: "a", name: "React.js", type: "TOOL", status: "ACTIVE", description: "Create interfaces with React." };
const b = { id: "b", name: "ReactJS", type: "TOOL", status: "ACTIVE", description: "Create interfaces with React." };
assert.equal(mergeProblem(a, { ...b, name: "React.js" }, [], 2, true), null);
assert.match(mergeProblem(a, { ...b, type: "DOMAIN" }, [], 2, false)!, /types/);
assert.match(mergeProblem(a, { ...b, externalId: "x" }, [], 6, true)!, /Semantic|limit/);
assert.match(mergeProblem({ ...a, externalId: "one" }, { ...b, externalId: "two" }, [], 1, false)!, /identities/);
assert.match(mergeProblem(a, b, [{ fromId: "a", toId: "b", kind: "PARENT" }], 1, false)!, /hierarchy/);
assert.match(mergeProblem(a, b, [{ fromId: "a", toId: "middle", kind: "PARENT" }, { fromId: "middle", toId: "b", kind: "PARENT" }], 1, false)!, /cycle/);
assert.match(mergeProblem({ ...a, policyLocked: true }, b, [], 1, false)!, /locked/);
assert.match(mergeProblem({ ...a, canonicalId: "b" }, b, [], 1, false)!, /canonical/);
const proposal = { name: "Harness routing", description: "Plan and validate physical routing of wiring harnesses.", supportingQuote: "Routed the harness around the bracket and checked bend radius.", rationale: "The contribution demonstrates physical routing and clearance validation." };
const artifact = { source: "CAD", title: "Harness change", body: proposal.supportingQuote, memberRole: "authored revision" };
assert.equal(proposalProblem(proposal, artifact, 0), null);
assert.match(proposalProblem(proposal, { ...artifact, source: "TASK" }, 0)!, /attributable/);
assert.match(proposalProblem({ ...proposal, supportingQuote: "Invented an unsupported passage for the proposal." }, artifact, 0)!, /passage/);
assert.match(proposalProblem(proposal, artifact, 1)!, /similar/);
assert.match(proposalProblem({ ...proposal, description: "Tool" }, artifact, 0)!, /definition/);
assert.deepEqual(validateGoals(["one", "one", "two"]), ["one", "two"]);
assert.throws(() => validateGoals(["1", "2", "3", "4"]));
assert.throws(() => validateGoals([12]));
assert.equal(matchOpportunity("Use Python to plot calibration data", [{ id: "py", name: "Python", aliases: ["Python 3"] }]).length, 1);
assert.equal(matchOpportunity("A pythonic implementation", [{ id: "py", name: "Python", aliases: [] }]).length, 0);
console.log("skillCatalog: identity, restrictive sharing, deduplicated credit, consolidation policy, cited creation and opportunity boundaries passed");
